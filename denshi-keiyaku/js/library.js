// 条項の実際の文言（有利文言を反映）を返す
// stance: 'neutral'（中立）／'favor'（自社に有利）
function resolveClause(c, ourRole, stance, typeId) {
  const f = stance === 'favor' && c.fav ? c.fav[ourRole] : null;
  const extra = c.favOnly === ourRole && stance === 'favor';
  const adv = (f || extra) ? ((ADVICE[typeId] || {})[c.id] || {})[ourRole] : null;
  return { ...c, text: f ? f.text : c.text, on: f && f.on !== undefined ? f.on : c.on,
    favNote: f ? f.note : (extra ? c.note : ''), changed: !!f, advice: adv || null, tip: (!f && !extra) ? (TIPS[c.id] || null) : null };
}
function clausesFor(t, ourRole, stance) {
  return t.clauses
    .filter(c => c.favOnly === undefined || (stance === 'favor' && c.favOnly === ourRole))
    .map(c => {
      const r = resolveClause(c, ourRole, stance, t.id);
      if (c.favOnly !== undefined) r.on = true;   // 有利用の追加条項は最初からオン
      return r;
    });
}

