function buildLibraryContract(opt) {
  const t = CONTRACT_LIBRARY.find(x => x.id === opt.type);
  const ko = opt.ourRole === 1 ? opt.partyName : opt.ourName;   // 甲
  const otsu = opt.ourRole === 1 ? opt.ourName : opt.partyName; // 乙
  const fill = s => s.replace(/\{\{甲\}\}/g, ko || '{{甲}}').replace(/\{\{乙\}\}/g, otsu || '{{乙}}')
    .replace(/\{\{([^{}]+)\}\}/g, (m, k) => (opt.values[k] || '').trim() ? opt.values[k].trim() : m);
  const all = clausesFor(t, opt.ourRole, opt.stance);
  const used = all.filter(c => c.req || (opt.on[c.id] !== undefined ? opt.on[c.id] : c.on !== false));
  const lines = [fill(t.preamble), ''];
  used.forEach((c, i) => { lines.push(`第${i + 1}条（${c.title}）`); lines.push(fill(c.text)); lines.push(''); });
  lines.push(fill(t.closing || CLOSING));
  let body = lines.join('\n');
  if (t.id === 'nda') {
    const no = id => used.findIndex(c => c.id === id) + 1;
    body = body.replace('第2条、第3条及び損害賠償に関する定め', `第${no('keep')}条、第${no('use')}条${no('dmg') ? '及び第' + no('dmg') + '条' : ''}`);
  }
  return { title: t.name.replace(/（.*）$/, ''), body, favored: used.filter(c => c.favNote).map(c => ({ title: c.title, note: c.favNote, advice: c.advice })) };
}

